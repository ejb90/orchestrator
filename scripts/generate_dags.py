"""Generate DOT sources and dependency-free SVG previews from the example specs.

Run from the repository root: uv run python scripts/generate_dags.py
Only visualization edges are transitively reduced; execution specs stay unchanged.
"""

from __future__ import annotations

import json
import runpy
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from orchestrator import compile_workflow  # noqa: E402

EXAMPLES = {
    "diamond": {},
    "nested": {"start": 3},
    "branches": {},
    "convergence": {},
    "command": {},
    "staging": {},
    "script": {},
}
COLORS = {"task": "#dbeafe", "decision": "#fef3c7", "enter": "#e2e8f0", "exit": "#e2e8f0"}


def diagram(spec: dict, title: str) -> tuple[str, str]:
    nodes = spec["nodes"]
    ranks: dict[str, int] = {}
    ancestors: dict[str, set[str]] = {}
    while len(ranks) < len(nodes):
        for name, node in nodes.items():
            if name in ranks or any(dep not in ranks for dep in node["deps"]):
                continue
            ranks[name] = max((ranks[dep] + 1 for dep in node["deps"]), default=0)
            ancestors[name] = set(node["deps"]).union(*(ancestors[dep] for dep in node["deps"]))
    edges = []
    for target, node in nodes.items():
        for source in node["deps"]:
            if not any(source in ancestors[other] for other in node["deps"] if other != source):
                edges.append((source, target))

    def label(name):
        node = nodes[name]
        description = "finalizer" if node["finalizer"] and node["kind"] == "task" else node["kind"]
        if node["when"]:
            description += f" · branch: {node['when'][1]}"
        return name, description

    dot = [
        "// Generated by scripts/generate_dags.py; visualization-only transitive reduction.",
        "// Guards, early completion, and finalizers remain coordinator-controlled.",
        "digraph workflow {",
        f"  graph [rankdir=TB, label={json.dumps(title)}, labelloc=t, fontname=Helvetica];",
        '  node [shape=box, style="rounded,filled", fontname=Helvetica, color="#64748b"];',
        '  edge [color="#64748b"];',
    ]
    for name in nodes:
        text, kind = label(name)
        color = COLORS[nodes[name]["kind"]]
        if kind == "finalizer":
            color = "#dcfce7"
        dot.append(
            f'  {json.dumps(name)} [label={json.dumps(text + chr(10) + kind, ensure_ascii=False)}, fillcolor="{color}"];'
        )
    dot += [f"  {json.dumps(source)} -> {json.dumps(target)};" for source, target in edges]
    dot.append("}")

    layers = [[n for n in nodes if ranks[n] == rank] for rank in range(max(ranks.values()) + 1)]
    width = max(len(layer) for layer in layers) * 340 + 40
    height = len(layers) * 100 + 70
    positions = {}
    for rank, layer in enumerate(layers):
        for column, name in enumerate(layer):
            positions[name] = ((width - len(layer) * 340) / 2 + column * 340 + 10, rank * 100 + 50)
    svg = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">',
        f'<title id="title">{escape(title)}</title>',
        '<desc id="desc">Workflow dependency graph. Task nodes are blue, decisions yellow, scope boundaries grey, and finalizers green.</desc>',
        '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="#64748b"/></marker></defs>',
        f'<rect width="{width}" height="{height}" fill="white"/>',
        f'<text x="{width / 2}" y="25" text-anchor="middle" font-family="sans-serif" font-size="18" fill="#0f172a">{escape(title)}</text>',
    ]
    for source, target in edges:
        x1, y1 = positions[source]
        x2, y2 = positions[target]
        svg.append(
            f'<path d="M {x1 + 160} {y1 + 64} L {x2 + 160} {y2 - 3}" stroke="#64748b" stroke-width="1.5" marker-end="url(#arrow)"/>'
        )
    for name in nodes:
        x, y = positions[name]
        text, kind = label(name)
        color = "#dcfce7" if kind == "finalizer" else COLORS[nodes[name]["kind"]]
        svg += [
            f'<rect x="{x}" y="{y}" width="320" height="64" rx="8" fill="{color}" stroke="#64748b"/>',
            f'<text x="{x + 160}" y="{y + 26}" text-anchor="middle" font-family="monospace" font-size="12" fill="#0f172a">{escape(text)}</text>',
            f'<text x="{x + 160}" y="{y + 47}" text-anchor="middle" font-family="sans-serif" font-size="12" fill="#334155">{escape(kind)}</text>',
        ]
    svg.append("</svg>")
    return "\n".join(dot) + "\n", "\n".join(svg) + "\n"


def main():
    destination = ROOT / "docs/assets/dags"
    destination.mkdir(parents=True, exist_ok=True)
    for name, inputs in EXAMPLES.items():
        workflow = runpy.run_path(str(ROOT / f"examples/{name}.py"))["workflow"]
        dot, svg = diagram(compile_workflow(workflow, inputs), name.title() + " workflow")
        (destination / f"{name}.dot").write_text(dot)
        (destination / f"{name}.svg").write_text(svg)
        print(f"Generated {name}.dot and {name}.svg")


if __name__ == "__main__":
    main()
